#!/bin/sh
# Compile FFV1 compute shaders (src/ffv1_shaders/*.comp) to SPIR-V and embed
# them as uint32 arrays in src/av1r_ffv1_spv.h.
# Usage: sh tools/ffv1_spv.sh <glslc>   (run from the package root)

GLSLC="$1"
OUT="src/av1r_ffv1_spv.h"
TMP="src/av1r_ffv1_spv.h.tmp"

{
  echo "// Generated by tools/ffv1_spv.sh from src/ffv1_shaders/*.comp - do not edit."
  echo "#pragma once"
  echo "#include <cstddef>"
  echo "#include <cstdint>"
} > "$TMP" || exit 1

for src in src/ffv1_shaders/*.comp; do
  name=$(basename "$src" .comp)
  echo "" >> "$TMP"
  echo "static const uint32_t av1r_ffv1_spv_${name}[] = {" >> "$TMP"
  if ! "$GLSLC" --target-env=vulkan1.1 -O -mfmt=num -o - "$src" >> "$TMP"; then
    echo "ERROR: glslc failed on $src"
    rm -f "$TMP"
    exit 1
  fi
  echo "};" >> "$TMP"
done

mv "$TMP" "$OUT"
